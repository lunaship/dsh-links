// Command loadgen drives DLR/1 capacity measurements against a local relay
// instance. It models real usage — a handful of long-lived streams per route
// doing periodic request/response roundtrips — not connection churn, because
// the pre-auth per-IP limiter (burst 32 / 30m) intentionally throttles churn.
// Concurrency comes from multiple enrolled hosts (routes), each opening up to
// default_max_streams_per_route streams.
//
// Usage (against an isolated local instance):
//
//	loadgen -agent 127.0.0.1:9444 -client 127.0.0.1:9443 \
//	  -admin http://127.0.0.1:8081 -admin-user admin \
//	  -admin-pass-file <file> -hosts 8 -streams 8 -duration 5m
package main

