/**
 * App 界面语言（与服务端 locale.preference 对齐：zh / en）。
 * 切换后立即刷新 Compose（CompositionLocal），并落盘本地缓存。
 *
 * 词条用 buildMap 承载，避免巨型构造/ mapOf 参数超过 ART 上限导致 VerifyError 闪退。
 */
object LocaleManager {
    private const val PREFS = "dsh_settings"
    private const val KEY = "app_settings_language"

    var language by mutableStateOf("zh")
        private set

    val strings: DshStrings
        get() = if (language == "en") DshStringsEn else DshStringsZh

    fun init(context: Context) {
        val prefs = context.getSharedPreferences(PREFS, Context.MODE_PRIVATE)
        language = normalize(prefs.getString(KEY, "zh"))
    }

    fun setLanguage(context: Context, code: String) {
        val next = normalize(code)
        if (language == next) return
        language = next
        context.getSharedPreferences(PREFS, Context.MODE_PRIVATE)
            .edit()
            .putString(KEY, next)
            .apply()
    }

    fun normalize(code: String?): String =
        if (code?.lowercase()?.startsWith("en") == true) "en" else "zh"
}

