        assertEquals("下载", DshStringsZh.tableDownload)
        assertEquals("Diagram", DshStringsEn.mermaidDiagram)
        assertEquals("示意图", DshStringsZh.mermaidDiagram)
        assertEquals("相册", DshStringsZh.choosePhoto)
        assertEquals("拍照", DshStringsZh.takePhoto)
        assertEquals("Photos", DshStringsEn.choosePhoto)
        assertEquals("Device & pairing", DshStringsEn.pairingManage)
        assertEquals("设备与配对", DshStringsZh.pairingManage)
        assertEquals("Thinking", DshStringsEn.thinkingActive)
        assertEquals("思考中", DshStringsZh.thinkingActive)
        assertEquals("Thought · %ds", DshStringsEn.thoughtForSeconds)
        assertEquals("思考 · %d秒", DshStringsZh.thoughtForSeconds)
        assertEquals("LAN", DshStringsEn.viaLan)
        assertEquals("局域网", DshStringsZh.viaLan)
        assertEquals("Cloud", DshStringsEn.viaCloud)
        assertEquals("云端", DshStringsZh.viaCloud)
        assertEquals("Scan to restore cloud", DshStringsEn.restoreCloudScan)
        assertEquals("扫码恢复云端", DshStringsZh.restoreCloudScan)
        assertEquals("Later", DshStringsEn.restoreCloudLater)
        assertEquals("稍后", DshStringsZh.restoreCloudLater)
        assertEquals("Rescan for cloud", DshStringsEn.restoreCloudTag)
        assertEquals("需扫码恢复云端", DshStringsZh.restoreCloudTag)
        assertEquals("Clear all", DshStringsEn.clearAllLocalRecords)
        assertEquals("一键清理", DshStringsZh.clearAllLocalRecords)
        assertEquals("Clear all", DshStringsEn.clearSectionRecords)
        assertEquals("全部清除", DshStringsZh.clearSectionRecords)
        assertEquals("连接已失效，请重新扫码配对", DshStringsZh.connectionAuthExpired)
        assertEquals("云端接入已更换或吊销。同一网络仍可连这台电脑；恢复云端请重新扫码。", DshStringsZh.relayRouteExpired)
        assertEquals("云端电脑未在线。请到插件点「重新连接」，或改用同一网络。", DshStringsZh.relayAgentOffline)
        assertEquals("Connection expired. Scan the QR code to pair again.", DshStringsEn.connectionAuthExpired)
        assertEquals("Cloud access was replaced or revoked. Same-network still works; scan again to restore cloud.", DshStringsEn.relayRouteExpired)
        assertEquals("The computer is offline. Tap Reconnect in the plugin, or use the same network.", DshStringsEn.relayAgentOffline)
        assertEquals("This phone is waiting for approval in the computer’s Phone link panel.", DshStringsEn.devicePendingApproval)
        assertEquals("设备待主机确认，请在电脑「手机连接」里批准后再进入", DshStringsZh.devicePendingApproval)
        assertEquals("上次发送可能未完成，已放回输入框，请确认后再发", DshStringsZh.sendParkedRestored)
        assertEquals("Last send may not have finished. It's back in the composer — check and send again.", DshStringsEn.sendParkedRestored)
        assertEquals("附件过大未保留，请重新添加图片", DshStringsZh.sendParkedImagesDropped)
        assertEquals("Attachments were too large to keep. Add the images again.", DshStringsEn.sendParkedImagesDropped)
        assertEquals("Couldn't load this conversation", DshStringsEn.loadConversationFailed)
        assertEquals("会话加载失败", DshStringsZh.loadConversationFailed)
        assertEquals("Couldn't load sessions", DshStringsEn.loadSessionListFailed)
        assertEquals("无法加载会话列表", DshStringsZh.loadSessionListFailed)
        assertEquals("Couldn't load workspaces", DshStringsEn.loadWorkspaceListFailed)
        assertEquals("无法加载工作区", DshStringsZh.loadWorkspaceListFailed)
        assertEquals("No Harness presets available", DshStringsEn.noAgentPresets)
        assertEquals("没有可用的 Harness 预设", DshStringsZh.noAgentPresets)
        assertEquals("正在配对…", DshStringsZh.pairingInProgress)
        assertEquals("Pairing…", DshStringsEn.pairingInProgress)
        assertEquals("主机证书已变更，请重新配对", DshStringsZh.certificateChanged)
        assertEquals("The computer certificate changed. Scan the QR code to pair again.", DshStringsEn.certificateChanged)
        assertEquals("需要审批", DshStringsZh.notifNeedApproval)
        assertEquals("Approval needed", DshStringsEn.notifNeedApproval)
        assertEquals("配对码无效或已过期，请在电脑端刷新后重试", DshStringsZh.pairCodeInvalid)
        assertEquals("Pairing code is invalid or expired. Refresh it on the computer and try again", DshStringsEn.pairCodeInvalid)
        assertEquals("〔图〕", DshStringsZh.shareFenceDiagram)
        assertEquals("[Diagram]", DshStringsEn.shareFenceDiagram)
        assertEquals("加载失败，点击重试", DshStringsZh.loadOlderRetry)
        assertEquals("Couldn't load earlier. Tap to retry", DshStringsEn.loadOlderRetry)
        assertEquals("配对失败：%s\n点击重试", DshStringsZh.pairFailedTapToRetry)
        assertEquals("Pairing failed: %s\nTap to try again", DshStringsEn.pairFailedTapToRetry)
        assertEquals("手机", DshStringsZh.phoneFallback)
        assertEquals("Phone", DshStringsEn.phoneFallback)
        assertEquals("无法保存分享的图片，文字仍会带入会话", DshStringsZh.shareImagesPersistFailed)
        assertEquals("Couldn't keep the shared images. The text is still in the chat", DshStringsEn.shareImagesPersistFailed)
        assertEquals("目前只能分享文字或图片到会话", DshStringsZh.shareUnsupported)
        assertEquals("Only text or images can be shared into a chat", DshStringsEn.shareUnsupported)
    }
}
