package dev.deeplinks.core

import org.junit.Assert.assertEquals
import org.junit.Test

class LocaleManagerTest {
    @Test
    fun normalize_mapsEnglishVariantsToEn() {
        assertEquals("en", LocaleManager.normalize("en"))
        assertEquals("en", LocaleManager.normalize("EN"))
        assertEquals("en", LocaleManager.normalize("en-US"))
    }

    @Test
    fun normalize_defaultsToZh() {
        assertEquals("zh", LocaleManager.normalize("zh"))
        assertEquals("zh", LocaleManager.normalize("zh-CN"))
        assertEquals("zh", LocaleManager.normalize(null))
        assertEquals("zh", LocaleManager.normalize(""))
        assertEquals("zh", LocaleManager.normalize("fr"))
    }

    @Test
    fun strings_switchWithLanguage() {
        assertEquals("Settings", DshStringsEn.settingsTitle)
        assertEquals("设置", DshStringsZh.settingsTitle)
        assertEquals("小", DshStringsZh.fontSizeSmall)
        assertEquals("标准", DshStringsZh.fontSizeDefault)
        assertEquals("大", DshStringsZh.fontSizeLarge)
        assertEquals("Small", DshStringsEn.fontSizeSmall)
        assertEquals("Default", DshStringsEn.fontSizeDefault)
        assertEquals("Large", DshStringsEn.fontSizeLarge)
        assertEquals("Share image", DshStringsEn.shareConversationImage)
        assertEquals("分享图片", DshStringsZh.shareConversationImage)
        assertEquals("Select text", DshStringsEn.selectText)
        assertEquals("选择文字", DshStringsZh.selectText)
        assertEquals("Share", DshStringsEn.shareMessage)
        assertEquals("分享", DshStringsZh.shareMessage)
        assertEquals("Couldn't delete workspace: %s", DshStringsEn.deleteWorkspaceFailed)
        assertEquals("删除工作区失败：%s", DshStringsZh.deleteWorkspaceFailed)
